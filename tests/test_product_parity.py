def test_selection_returns_distinct_champions(artifact):
    """The whole point of hierarchical diversity."""
    for objective in ("ev", "p1"):
        sel = select(artifact, objective, "none", k=3)
        champs = {candidate_summary(artifact, i)["champion_id"] for i in sel}
        assert len(sel) == 3
        assert len(champs) == 3, f"{objective} returned {len(champs)} distinct champions"


def test_objectives_select_different_brackets(artifact):
    """EV and P(1st) are near-orthogonal; identical output would be suspicious."""
    assert select(artifact, "ev", "none", k=3) != select(artifact, "p1", "none", k=3)


def test_selection_is_deterministic(artifact):
    for _ in range(3):
        assert select(artifact, "p1", "s16_at_least_2_double_digit", k=3) == select(
            artifact, "p1", "s16_at_least_2_double_digit", k=3
        )


def test_preference_actually_constrains(artifact):
    """Returned brackets must satisfy the requested preference."""
    for i in select(artifact, "ev", "s16_at_least_2_double_digit", k=3):
        assert artifact["candidates"][i]["dd16"] >= 2
    for i in select(artifact, "ev", "s16_no_double_digit", k=3):
        assert artifact["candidates"][i]["dd16"] == 0


def test_unknown_objective_or_preference_raises(artifact):
    """v1 exposes exactly two objectives; a typo must not silently fall back."""
    with pytest.raises(ValueError, match="unknown objective"):
        select(artifact, "balanced", "none")
    with pytest.raises(ValueError, match="unknown preference"):
        select(artifact, "ev", "contrarian")


