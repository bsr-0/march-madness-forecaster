def test_frequencies_come_from_the_full_bank_not_the_candidates(artifact):
    """Counting candidates would bias every user-facing frequency.

    The sampler over-samples unlikely champions on purpose, so the candidate list
    is not a probability sample.
    """
    pref = "s16_at_least_2_double_digit"
    shipped = constraint_frequency(artifact, pref)
    counted = sum(1 for c in artifact["candidates"] if c["dd16"] >= 2) / len(artifact["candidates"])
    assert shipped == artifact["constraint_probabilities"][pref]
    assert abs(shipped - counted) > 1e-6, (
        "candidate-counted frequency coincidentally equals the full-bank value; "
        "this test can no longer detect the substitution"
    )


def test_why_this_differs_describes_a_real_difference(artifact):
    ev_sel = select(artifact, "ev", "none", k=3)
    p1_sel = select(artifact, "p1", "none", k=3)
    reasons = why_this_differs(artifact, p1_sel[0], ev_sel[0])
    assert reasons and all(isinstance(r, str) and r.endswith(".") for r in reasons)
    assert not any("better" in r.lower() or "worse" in r.lower() for r in reasons), (
        "explanations must not claim one bracket is better; the objectives are "
        "near-orthogonal and the honest framing is 'different'"
    )
