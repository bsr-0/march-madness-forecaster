"""Historical men's NCAA tournament game results for backtesting.

Provides actual tournament outcomes used by KaggleBacktester to compute
Brier scores against the pipeline's predictions.

Each game includes: year, round, team seeds, team IDs, winner, scores.
Data loaded from ``tournament_results_{year}.json`` files in the
historical data directory.

Tournament result JSON files can be generated by:
1. Downloading Kaggle March Machine Learning Mania CSVs
   (MNCAATourneyCompactResults.csv) and converting
2. Scraping Sports Reference bracket pages
3. Manual creation from published NCAA bracket results

The 67 games per tournament cover:
  FF (4 games), R64 (32), R32 (16), S16 (8), E8 (4), F4 (2), NCG (1)
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)


@dataclass
class TournamentGame:
    """A single tournament game result."""
    year: int
    round_name: str  # "R64", "R32", "S16", "E8", "F4", "NCG"
    team1_id: str
    team2_id: str
    team1_seed: int
    team2_seed: int
    team1_score: int
    team2_score: int
    team1_won: bool
    region: str = ""

    @property
    def upset(self) -> bool:
        if self.team1_won:
            return self.team1_seed > self.team2_seed
        return self.team2_seed > self.team1_seed

    @property
    def winner_id(self) -> str:
        return self.team1_id if self.team1_won else self.team2_id

    @property
    def loser_id(self) -> str:
        return self.team2_id if self.team1_won else self.team1_id

    def to_eval_dict(self) -> Dict:
        """Format for KaggleBacktester.evaluate_predictions()."""
        return {
            "team1_id": self.team1_id,
            "team2_id": self.team2_id,
            "team1_seed": self.team1_seed,
            "team2_seed": self.team2_seed,
            "team1_won": self.team1_won,
            "round": self.round_name,
            "team1_score": self.team1_score,
            "team2_score": self.team2_score,
        }


def load_tournament_results(
    year: int,
    data_dir: str = "data/raw/historical",
) -> List[TournamentGame]:
    """Load tournament results for a given year.

    Tries JSON file first, falls back to hardcoded data.
    """
    path = Path(data_dir) / f"tournament_results_{year}.json"
    if path.exists():
        with open(path) as f:
            data = json.load(f)
        games = data if isinstance(data, list) else data.get("games", [])
        return [
            TournamentGame(
                year=g["year"],
                round_name=g["round_name"],
                team1_id=g["team1_id"],
                team2_id=g["team2_id"],
                team1_seed=g["team1_seed"],
                team2_seed=g["team2_seed"],
                team1_score=g.get("team1_score", 0),
                team2_score=g.get("team2_score", 0),
                team1_won=g["team1_won"],
                region=g.get("region", ""),
            )
            for g in games
        ]

    # Fall back to hardcoded data
    hardcoded = _HARDCODED.get(year, [])
    if not hardcoded:
        logger.warning("No tournament results for year %d", year)
    return hardcoded


def save_tournament_results(
    games: List[TournamentGame],
    year: int,
    data_dir: str = "data/raw/historical",
) -> None:
    """Save tournament results to JSON for a given year."""
    path = Path(data_dir) / f"tournament_results_{year}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(
            {"year": year, "games": [asdict(g) for g in games]},
            f, indent=2,
        )
    logger.info("Saved %d tournament games to %s", len(games), path)


def get_available_years(data_dir: str = "data/raw/historical") -> List[int]:
    """Return years for which tournament results are available."""
    years = set(_HARDCODED.keys())
    p = Path(data_dir)
    if p.is_dir():
        for f in p.glob("tournament_results_*.json"):
            try:
                yr = int(f.stem.split("_")[-1])
                years.add(yr)
            except ValueError:
                pass
    return sorted(years)


def get_tournament_games_for_eval(
    year: int,
    data_dir: str = "data/raw/historical",
) -> List[Dict]:
    """Return tournament games in the format expected by KaggleBacktester.evaluate_predictions()."""
    games = load_tournament_results(year, data_dir)
    return [g.to_eval_dict() for g in games]


# Hardcoded results will be populated via scraping or manual entry.
# For now, this is a placeholder that defers to JSON files.
_HARDCODED: Dict[int, List[TournamentGame]] = {}
